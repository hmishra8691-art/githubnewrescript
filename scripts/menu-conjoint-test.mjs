/**
 * MENU-BASED CONJOINT — design → question → respondent → export columns.
 *
 *   Design Generators offers "Menu-Based Conjoint (MBC)" with the items /
 *   price-points editor; the picker offers Menu-Based Conjoint with its
 *   Pricing / Configurator preset beside it
 *       ↓
 *   Runtime: every task is the whole menu at that task's prices; the base is
 *   pre-selected and locked; ticking updates the total; "nothing" is
 *   exclusive; the max is enforced; required means every menu decided
 *       ↓
 *   the answer is {task: [items]} and flattens to VAR_T<n>_<item> / _NONE /
 *   _TOTAL — from the prices this respondent actually saw
 */
import { openHarness, assert } from "./lib/variantHarness.mjs";
import { openPreview } from "./lib/preview.mjs";
import { menuPlugin } from "../packages/designs/dist/menu.js";

const RUNTIME = process.env.RUNTIME_URL ?? "http://localhost:3001";
const h = await openHarness();

console.log("\nSTUDIO — the generator and the picker know about menus");
await h.goTab("Design Generators");
await h.page.waitForSelector('button:has-text("Menu-Based Conjoint (MBC)")');
await h.page.click('button:has-text("Menu-Based Conjoint (MBC)")');
await h.page.waitForSelector('text=Menu items & price points');
assert.ok(await h.page.$('text=Always-included items (base product)'), "the configurator's base-item field is there");
assert.ok(await h.page.$('button:has-text("+ attribute")'), "items are edited with the attributes editor — one editor, two uses");
await h.page.click('button:has-text("close")');
const menu = await h.createFromPicker("conjoint", "conjoint.menu");
assert.equal(menu.type, "conjoint_task");
assert.equal(menu.variant, "conjoint.menu");
await h.goTab("Questions");
await h.page.click('[data-testid="add-question-top"]');
await h.page.waitForSelector('[data-testid="picker-family-conjoint"]');
await h.page.click('[data-testid="picker-family-conjoint"]');
await h.page.waitForSelector('[data-testid="picker-type-conjoint.menu"]');
assert.ok(await h.page.$('[data-testid="picker-type-conjoint.menu"] ~ * [data-preset-of="conjoint.menu"], [data-preset-of="conjoint.menu"]'), "Pricing / Configurator is a preset beside Menu-Based Conjoint");
assert.ok(!(await h.page.$('[data-testid="picker-variant-conjoint.menu_based_conjoint"]')), "the old planned placeholder is gone");
await h.page.click('.modal-back button:has-text("close")');
await h.page.waitForSelector(".modal-back", { state: "detached" });
console.log("  ok   MBC generator form, conjoint.menu type, pricing_configurator preset");

/* the design, generated by the same plugin the Studio uses, then attached */
const config = {
  items: [
    { name: "Base plan", levels: ["$10", "$15"] },
    { name: "Extra storage", levels: ["$2", "$4"] },
    { name: "Priority support", levels: ["$3", "$5"] },
  ],
  requiredItems: ["Base plan"],
  tasks: 3, versions: 1, noneOption: true, minSelections: 0, maxSelections: 2, currency: "$",
};
const gen = menuPlugin.generate(config, 11);
const def = {
  meta: { id: "sandbox", code: "MBC", title: "Menu", version: "1.0" },
  designs: [{ id: "menu1", kind: "menu", name: "Plans", version: 1, seed: 11, config, file: { format: "json", columns: gen.columns, rows: gen.rows } }],
  questions: [
    { id: "m", code: "M1", variableName: "PLAN", type: "conjoint_task", variant: "conjoint.menu", text: "Which of these would you buy at these prices?", required: true, settings: { designRef: "menu1" } },
    { id: "q2", code: "Q2", variableName: "Q2", type: "single_select", text: "Done?", options: [{ code: 1, label: "Yes" }] },
  ],
  flow: [{ type: "page", id: "p1", questionIds: ["m"] }, { type: "page", id: "p2", questionIds: ["q2"] }, { type: "end", id: "e1", status: "complete" }],
};
await h.loadDef(def);
const stored = await h.readDef();
const priceOf = (task, item) => gen.rows.find((r) => String(r.task) === String(task) && String(r.item) === String(item));

console.log("\nRUNTIME — the menu: base locked, ticking totals, nothing exclusive, max enforced");
const pv = await openPreview(h.browser, RUNTIME, { definition: stored }, { selector: '[data-testid="rs-menu-tasks"]' });
const tasks = await pv.$$('[data-testid="rs-menu-task"]');
assert.equal(tasks.length, 3, "three menus, one per task");
const t1 = '[data-testid="rs-menu-task"][data-task="1"]';
const prices = await pv.$$eval(`${t1} [data-testid="rs-menu-price"]`, (els) => els.map((e) => e.textContent));
assert.deepEqual(prices, [priceOf(1, 1).price, priceOf(1, 2).price, priceOf(1, 3).price], "the prices shown are the design's, in menu order");
assert.ok(await pv.$eval(`${t1} [data-item="1"] input`, (e) => e.checked && e.disabled), "the base is pre-selected and locked");
assert.match(await pv.textContent(`${t1} [data-testid="rs-menu-total"]`), new RegExp(`0 add-ons \\+ baseTotal: \\$${priceOf(1, 1).price_value}`), "total = base alone to start");
await pv.click(`${t1} [data-item="2"]`);
await pv.waitForTimeout(80);
assert.match(await pv.textContent(`${t1} [data-testid="rs-menu-total"]`), new RegExp(`1 add-on \\+ baseTotal: \\$${priceOf(1, 1).price_value + priceOf(1, 2).price_value}`));
assert.deepEqual(await h.answerOf(pv, "m"), { "1": ["2"] }, "the answer is the chosen add-ons per task; the base is implied");
// max 2 counts the base: a second add-on is refused
await pv.click(`${t1} [data-item="3"]`);
await pv.waitForTimeout(80);
assert.deepEqual(await h.answerOf(pv, "m"), { "1": ["2"] }, "base + 2 add-ons would be 3 > max 2 → the click does nothing");
assert.equal(await pv.$eval(`${t1} [data-item="3"] input`, (e) => e.checked), false);
// nothing is exclusive
const t2 = '[data-testid="rs-menu-task"][data-task="2"]';
await pv.click(`${t2} [data-item="2"]`);
await pv.click(`${t2} [data-testid="rs-menu-none"]`);
await pv.waitForTimeout(80);
assert.deepEqual((await h.answerOf(pv, "m"))["2"], ["none"]);
assert.match(await pv.textContent(`${t2} [data-testid="rs-menu-total"]`), /Nothing selected/);
assert.equal(await pv.$eval(`${t2} [data-item="1"] input`, (e) => e.checked), false, "even the base is unticked under 'nothing'");
console.log("  ok   prices from the design; base locked; total live; max counts the base; nothing is exclusive");

console.log("\nRUNTIME — required: every menu decided (the base alone is a decision)");
await h.next(pv);
await pv.waitForTimeout(200);
assert.match(await pv.evaluate(() => document.body.innerText), /Please answer task 3/, "task 3 never touched");
assert.ok(await pv.$('[data-testid="rs-menu-tasks"]'), "still on the page");
const t3 = '[data-testid="rs-menu-task"][data-task="3"]';
await pv.click(`${t3} [data-item="3"]`);
await pv.click(`${t3} [data-item="3"]`); // tick and untick: an empty list, i.e. "just the base"
await pv.waitForTimeout(80);
assert.deepEqual((await h.answerOf(pv, "m"))["3"], []);
await h.next(pv);
await pv.waitForSelector('[data-qid="q2"]');
console.log("  ok   refused until decided; base-only accepted");

console.log("\nEXPORT — the flattened columns say what was bought at what total");
// flatten in the browser through the same engine the runtime bundles
const flat = await pv.evaluate(() => {
  const st = window.__rescriptState;
  return st?.answers;
});
assert.deepEqual(flat.m, { "1": ["2"], "2": ["none"], "3": [] });
const { flattenVariables, createResponseState, setAnswer } = await import("../packages/engine/dist/index.js");
const { SurveyDefinition } = await import("../packages/schema/dist/index.js");
const parsed = SurveyDefinition.parse(stored);
const state = createResponseState(parsed, { seed: 1 });
setAnswer(parsed, state, "m", flat.m);
const cols = flattenVariables(parsed, state);
assert.equal(cols.PLAN_T1_1, 1); assert.equal(cols.PLAN_T1_2, 1); assert.equal(cols.PLAN_T1_3, 0); assert.equal(cols.PLAN_T1_NONE, 0);
assert.equal(cols.PLAN_T1_TOTAL, priceOf(1, 1).price_value + priceOf(1, 2).price_value);
assert.equal(cols.PLAN_T2_NONE, 1); assert.equal(cols.PLAN_T2_1, 0); assert.equal(cols.PLAN_T2_TOTAL, 0);
assert.equal(cols.PLAN_T3_1, 1); assert.equal(cols.PLAN_T3_2, 0); assert.equal(cols.PLAN_T3_TOTAL, priceOf(3, 1).price_value);
console.log(`  ok   PLAN_T1 = base+storage $${cols.PLAN_T1_TOTAL}; T2 nothing; T3 base only $${cols.PLAN_T3_TOTAL}`);
await pv.close();

await h.close();
console.log("\nALL MENU CONJOINT CHECKS PASSED");
