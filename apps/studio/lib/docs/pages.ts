/** where the pages are: beside the app (the deploy includes them), or the repo checkout when run from elsewhere */
export function docsDir(): string {
  const candidates = [join(process.cwd(), "content", "docs"), join(process.cwd(), "apps", "studio", "content", "docs")];
  return candidates.find((d) => existsSync(d)) ?? candidates[0];
}

export function readDoc(slug: string): string | null {
  if (!/^[a-z0-9-]+$/.test(slug)) return null;
  const path = join(docsDir(), `${slug}.md`);
  return existsSync(path) ? readFileSync(path, "utf8") : null;
}

export function listDocs(): DocPage[] {
  const dir = docsDir();
  const present = new Set(existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md")).map((f) => f.slice(0, -3)) : []);
  const described = new Map(DOC_ORDER.map((d) => [d.slug, d.description]));
  return readingOrder().filter((d) => present.has(d.slug)).map((d) => {
    const md = readDoc(d.slug) ?? "";
    const r = renderMarkdown(md);
    return {
      slug: d.slug, title: r.title || d.slug, description: r.meta.summary ?? described.get(d.slug) ?? "",
      generated: md.includes("generated by scripts/gen-public-docs.mjs"), category: d.category.key, categoryLabel: d.category.label, group: d.group.label,
    };
  });
}

/** Previous / Next in reading order, and the related pages a page names (front matter `related: a, b`) */
export function neighbours(slug: string, related: string | undefined): { prev: DocPage | null; next: DocPage | null; related: DocPage[] } {
  const pages = listDocs();
  const i = pages.findIndex((p) => p.slug === slug);
  const rel = (related ?? "").split(",").map((x) => x.trim()).filter(Boolean).map((r) => pages.find((p) => p.slug === r)).filter((p): p is DocPage => !!p);
  return { prev: i > 0 ? pages[i - 1] : null, next: i >= 0 && i < pages.length - 1 ? pages[i + 1] : null, related: rel };
}

/** what the search box searches: each page's title, summary, headings and plain text */
export function searchIndex(): { slug: string; title: string; description: string; category: string; headings: string[]; text: string }[] {
  return listDocs().map((p) => {
    const r = renderMarkdown(readDoc(p.slug) ?? "");
    const text = r.html.replace(/<!--[\s\S]*?-->/g, " ").replace(/<[^>]+>/g, " ").replace(/&[a-z]+;/g, " ").replace(/\s+/g, " ").slice(0, 6000);
    return { slug: p.slug, title: p.title, description: p.description, category: p.categoryLabel, headings: r.headings.filter((h) => h.level === 2 || h.level === 3).map((h) => h.text), text };
  });
}

export { DOC_NAV, homeOf };

export function renderDoc(slug: string): (RenderedDoc & { slug: string }) | null {
  const md = readDoc(slug);
  if (md === null) return null;
  return { slug, ...renderMarkdown(md) };
}
