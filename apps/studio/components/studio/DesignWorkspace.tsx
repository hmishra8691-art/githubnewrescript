/**
 * DESIGN GENERATORS → METHODS (2026-11-09). Every method in one readable library:
 *   · the choice and experimental designs (a design file): Sample — a worked example generated by the real
 *     generator, read as tasks with its quality figures; Guided — the generator's own settings with a live
 *     recommendation and its reasons; Describe it — in words or by voice, read into a recommended configuration with
 *     what was assumed, what is missing (asked), and why. All three end in the same generator form: generate,
 *     review, edit, regenerate, export.
 *   · every study methodology (a complete study): its worked sample built by the real builder, then Study design to
 *     configure and add it.
 * One engine throughout — the registered generators, designAdvice, the methodology builders. Nothing parallel.
 */
const DESIGN_KINDS: DesignKind[] = ["conjoint", "maxdiff", "acbc", "menu", "cva", "experiment"];
const DESCRIPTIONS: Record<string, string> = {
  conjoint: "Choose between full product profiles — trade-offs, prices, shares, willingness to pay.",
  maxdiff: "Most and least important from small sets — a ratio-scaled ranking of 8–40 items.",
  acbc: "Build-your-own, screening and a tournament — many attributes, adapted to each respondent.",
  menu: "Tick what you would buy from a priced menu — bundles, add-ons, configurators.",
  cva: "Rate profiles — individual part-worths from small or specialist samples.",
  experiment: "Full or D-optimal fractional factorial, Latin square, Williams, balanced incomplete blocks.",
  custom: "A free-form file from column rules — fielding plans, rotation cells.",
};

export function designLibraryGroups(): LibraryGroup[] {
  const cats = [...new Set(STUDY_METHODOLOGIES.map((m) => m.category))] as StudyCategory[];
  return [
    { key: "designs", label: "Choice & experimental designs", note: "generates a design file", methods: [...DESIGN_KINDS, "custom" as const].flatMap((k) => [
      { id: `design:${k}`, name: k === "custom" ? "Design file from columns (advanced)" : DESIGN_KIND_NAMES[k as DesignKind], description: DESCRIPTIONS[k] },
      ...Object.entries(DESIGN_VARIANTS).filter(([, v]) => v.kind === k).map(([id, v]) => ({ id: `design:${id}`, name: v.name, description: v.description })),
    ]) },
    ...cats.map((c) => ({ key: c, label: CATEGORY_NAMES[c], note: "builds a complete study", methods: STUDY_METHODOLOGIES.filter((m) => m.category === c).map((m) => ({ id: `study:${m.id}`, name: m.name, description: m.fit })) })),
  ];
}

export function DesignWorkspace({ renderForm }: { renderForm(kind: string, initialConfig: Record<string, unknown> | undefined, initialName: string | undefined, onClose: () => void): React.ReactNode }) {
  const pending = React.useMemo(() => takePendingDesignRequest(), []);
  const [selected, setSelected] = React.useState<string | null>(pending ? (() => { const r = readDesignRequest(pending); const k = recommendDesign(r).kind; return `design:${k === "conjoint" && r.partial ? "conjoint@partial" : k}`; })() : null);
  const groups = React.useMemo(() => designLibraryGroups(), []);
  return (
    <div className="dw" data-testid="design-workspace">
      <div className="dw-lib">
        <h3 className="sec" style={{ marginTop: 0 }}>Methods</h3>
        <MethodLibrary groups={groups} selected={selected} onSelect={setSelected} />
      </div>
      <div className="dw-main">
        {!selected && <div className="dw-empty"><b>Pick a method.</b> Each opens with a worked sample generated by the real engine; then set it up step by step, or describe what you need in your own words.</div>}
        {selected?.startsWith("design:") && <DesignMethod key={selected} kind={selected.slice(7)} pending={pending} renderForm={renderForm} />}
        {selected?.startsWith("study:") && <StudyMethod key={selected} id={selected.slice(6)} />}
      </div>
    </div>
  );
}

/* ------------------------------------------------------------------ a design-file method */

type Tab = "sample" | "guided" | "describe";

function DesignMethod({ kind: methodId, pending, renderForm }: { kind: string; pending: string | null; renderForm: Parameters<typeof DesignWorkspace>[0]["renderForm"] }) {
  const s = useStudio();
  /* a variant (partial-profile CBC) is its kind's generator with the variant's sample and settings */
  const variant = DESIGN_VARIANTS[methodId];
  const kind: string = variant?.kind ?? methodId;
  const sample = variant ?? DESIGN_SAMPLES[kind as keyof typeof DESIGN_SAMPLES];
  const plugin = designGeneratorRegistry.get(kind)!;
  const [tab, setTab] = React.useState<Tab>(pending ? "describe" : "sample");
  const [form, setForm] = React.useState<{ config?: Record<string, unknown>; name?: string; n: number }>({ n: 0 });
  const [objective, setObjective] = React.useState(sample?.objective ?? "");
  const openForm = (config: Record<string, unknown> | undefined, name?: string) => { setForm((f) => ({ config, name, n: f.n + 1 })); setTab("guided"); };
  const sampleFile = React.useMemo(() => { try { return sample ? plugin.generate(structuredClone(sample.config) as never, 20261109) : null; } catch { return null; } }, [sample, plugin]);

  return (
    <div className="dm" data-testid={`design-method-${methodId}`}>
      <div className="dm-head">
        <h3>{variant ? variant.name : kind === "custom" ? "Design file from columns" : DESIGN_KIND_NAMES[kind as DesignKind]}</h3>
        <p className="dm-desc">{variant ? variant.description : plugin.description ?? DESCRIPTIONS[kind]}</p>
      </div>
      <div className="dm-tabs" role="tablist">
        {(["sample", "guided", "describe"] as Tab[]).map((t) => (
          <button key={t} type="button" role="tab" aria-selected={tab === t} className={`dm-tab${tab === t ? " on" : ""}`} onClick={() => setTab(t)} data-testid={`dm-tab-${t}`}>
            {t === "sample" ? "Sample" : t === "guided" ? "Guided set-up" : "Describe it"}
          </button>
        ))}
      </div>

      {tab === "sample" && sample && (
        <div className="dm-panel" data-testid="dm-sample">
          <div className="dm-sample-head">
            <div><b>{sample.title}</b><p className="dm-desc">{sample.objective}</p></div>
            <button type="button" className="btn primary small" onClick={() => openForm(structuredClone(sample.config), `${sample.title} — ${variant?.name ?? plugin.label}`)} data-testid="dm-use-sample">Use this sample as a starting point</button>
          </div>
          <SampleParameters kind={kind} config={sample.config} />
          {sampleFile ? <DesignPreview kind={kind} file={sampleFile} /> : <p className="sd-warn">The sample could not be generated.</p>}
          {sample.request && <p className="dm-desc">Written as a request, this sample is: <i>“{sample.request}”</i> <button type="button" className="linkish" onClick={() => setTab("describe")}>try it in Describe it</button></p>}
        </div>
      )}

      {tab === "guided" && (
        <div className="dm-panel" data-testid="dm-guided">
          <label className="f"><span>Research objective (what decision this design informs)</span>
            <input className="input" value={objective} onChange={(e) => setObjective(e.target.value)} data-testid="dm-objective" /></label>
          <p className="dm-desc">Set the design below. The recommendation under the form reacts to what you enter — tasks, alternatives, items per task, sample — and says why; <b>Generate Design File</b> builds, checks and attaches it.</p>
          <div key={form.n}>{renderForm(kind, form.config, form.name, () => setForm((f) => ({ n: f.n + 1 })))}</div>
        </div>
      )}

      {tab === "describe" && <Describe kind={kind as DesignKind} initial={pending ?? (sample?.request ?? "")} surveyId={s.surveyDbId} onUse={(rec, name) => openForm(rec.config, name)} />}
    </div>
  );
}

function SampleParameters({ kind, config }: { kind: string; config: Record<string, unknown> }) {
  const attrs = (config.attributes ?? config.factors ?? config.items) as unknown;
  const rows: [string, string][] = [];
  if (Array.isArray(attrs) && attrs.length && typeof attrs[0] === "object") for (const a of attrs as { name: string; levels: string[] }[]) rows.push([a.name, a.levels.join(" · ")]);
  else if (Array.isArray(attrs)) rows.push(["Items", (attrs as string[]).join(" · ")]);
  const params = Object.entries(config).filter(([k, v]) => !["attributes", "factors", "items", "prohibitions", "columnsSpec"].includes(k) && (typeof v === "number" || typeof v === "boolean" || typeof v === "string"));
  return (
    <div className="dm-params" data-testid="dm-params">
      {rows.length > 0 && <table className="dm-attrs"><tbody>{rows.map(([n, l]) => <tr key={n}><th>{n}</th><td>{l}</td></tr>)}</tbody></table>}
      {params.length > 0 && <div className="dm-chips">{params.map(([k, v]) => <span key={k} className="chip">{k.replace(/([A-Z])/g, " $1").toLowerCase()}: {String(v)}</span>)}</div>}
      {kind === "custom" && Array.isArray(config.columnsSpec) && <div className="dm-chips">{(config.columnsSpec as string[]).map((c) => <span key={c} className="chip">{c}</span>)}</div>}
    </div>
  );
}

/* ------------------------------------------------------------------ describe it (words or voice) */

function Describe({ kind, initial, surveyId, onUse }: { kind: DesignKind; initial: string; surveyId: string; onUse(rec: DesignRecommendation, name: string): void }) {
  const [text, setText] = React.useState(initial);
  const [answers, setAnswers] = React.useState<Record<string, string>>({});
  const [heard, setHeard] = React.useState<HeardTranscript | null>(null);
  const [read, setRead] = React.useState<ReturnType<typeof readDesignRequest> | null>(null);
  const rec = React.useMemo(() => {
    if (!read) return null;
    const a: { attributes?: { name: string; levels: string[] }[]; items?: string[]; treatments?: string[]; kind?: DesignKind } = { kind: read.kind ?? kind };
    if (answers.attributes || answers.factors || answers.prices) a.attributes = parseAttributes(answers.attributes || answers.factors || answers.prices);
    if (answers.items) a.items = answers.items.split("\n").map((x) => x.trim()).filter(Boolean);
    if (answers.treatments) a.treatments = answers.treatments.split("\n").map((x) => x.trim()).filter(Boolean);
    return recommendDesign(read, a);
  }, [read, answers, kind]);
  /* the rules read it at once; with "Read it with AI" on, the server's model reading (metered, only names you said)
     replaces it when it arrives — any failure keeps the rules' reading */
  const [useAi, setUseAi] = React.useState(true);
  const [reading, setReading] = React.useState<{ busy: boolean; note: string | null; source: "rules" | "ai" | null }>({ busy: false, note: null, source: null });
  const understand = async () => {
    const t = text;
    setRead(readDesignRequest(t)); setAnswers({});
    if (!useAi) { setReading({ busy: false, note: null, source: "rules" }); return; }
    setReading({ busy: true, note: null, source: null });
    try {
      const r = await fetch("/api/designs/interpret", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ text: t, surveyId, useAi }) });
      const j = await r.json().catch(() => null);
      if (r.ok && j?.read) { setRead(j.read); setReading({ busy: false, note: j.note ?? null, source: j.source ?? "rules" }); }
      else setReading({ busy: false, note: j?.error ? `Read by the rules — ${j.error}` : "Read by the rules.", source: "rules" });
    } catch { setReading({ busy: false, note: "Read by the rules — the AI could not be reached.", source: "rules" }); }
  };
  return (
    <div className="dm-panel" data-testid="dm-describe">
      <label className="f"><span>Describe the design you need — the method, attributes and levels or items, tasks, alternatives, constraints, sample, time</span>
        <textarea className="ta" rows={4} value={text} onChange={(e) => { setText(e.target.value); setHeard(null); }} data-testid="dm-describe-text"
          placeholder="I want a choice-based conjoint with six attributes and three to four levels per attribute, an efficient balanced design, 12 choice tasks and three alternatives per task." /></label>
      <HeardNote heard={heard} onUseOriginal={heard ? () => { setText((t) => t.replace(heard.english ?? "", heard.text)); setHeard(null); } : undefined} />
      <div className="row" style={{ gap: 8 }}>
        <button type="button" className="btn primary small" disabled={text.trim().length < 6 || reading.busy} onClick={understand} data-testid="dm-understand">Recommend a design</button>
        <label className="row" style={{ gap: 6, fontSize: 13 }} title="One AI request on this project, charged like other AI requests; it can only add names you actually said."><input type="checkbox" checked={useAi} onChange={(e) => setUseAi(e.target.checked)} data-testid="dm-use-ai" /> Read it with AI too</label>
        <VoiceButton surveyId={surveyId} label="Speak instead" refusedMessage="Microphone access was refused — allow it in the browser to describe the design by voice."
          onHeard={(h) => { const w = (h.english || h.text).trim(); if (!w) return; setText((t) => `${t.trim()}${t.trim() ? " " : ""}${w}`); setHeard(h.english && h.language !== "en" ? h : null); }} />
      </div>
      {reading.busy && <p className="dm-desc" data-testid="dm-reading">The AI is reading it…</p>}
      {read && rec && (
        <div className="dm-rec" data-testid="dm-recommendation" data-kind={rec.kind} data-source={reading.source ?? "rules"}>
          {reading.note && <p className="dm-desc" data-testid="dm-reading-note">{reading.note}</p>}
          {read.understood.length > 0 && <div><b>Understood</b><ul>{read.understood.map((u) => <li key={u}>{u}</li>)}</ul></div>}
          <div><b>Recommended: {DESIGN_KIND_NAMES[rec.kind]}</b><ul data-testid="dm-why">{rec.why.map((w) => <li key={w}>{w}</li>)}</ul></div>
          {rec.assumptions.length > 0 && <div><b>Assumed</b><ul>{rec.assumptions.map((w) => <li key={w}>{w}</li>)}</ul></div>}
          {rec.warnings.length > 0 && <div className="sd-warn" data-testid="dm-warnings">{rec.warnings.map((w) => <div key={w}>{w}</div>)}</div>}
          {rec.questions.length > 0 && (
            <div className="dm-questions" data-testid="dm-questions">
              <b>Still needed</b>
              {rec.questions.map((q) => (
                <label key={q.key} className="f"><span>{q.ask}</span>
                  <textarea className="ta" rows={3} value={answers[q.key] ?? ""} placeholder={q.example} onChange={(e) => setAnswers({ ...answers, [q.key]: e.target.value })} data-testid={`dm-answer-${q.key}`} /></label>
              ))}
              <p className="dm-desc">Until these are filled in, the configuration holds clearly named placeholders — the design can still be generated to see its structure.</p>
            </div>
          )}
          <div className="row" style={{ gap: 12, flexWrap: "wrap" }}>
            {rec.minSample != null && <span className="chip">Sample ≥ {rec.minSample}</span>}
            {rec.minutes != null && <span className="chip">≈ {rec.minutes} min of tasks</span>}
            <span className="grow" />
            <button type="button" className="btn primary small" onClick={() => onUse(rec, `${DESIGN_KIND_NAMES[rec.kind]} design`)} data-testid="dm-use-recommendation">Open in the guided set-up to review and generate</button>
          </div>
        </div>
      )}
    </div>
  );
}

/* ------------------------------------------------------------------ a study methodology */

function StudyMethod({ id }: { id: string }) {
  const cmd = useCommands();
  const m = STUDY_METHODOLOGIES.find((x) => x.id === id)!;
  const built = React.useMemo(() => {
    try {
      const empty = SurveyDefinition.parse({ meta: { id: "sample", code: "SAMPLE", title: m.name }, questions: [], flow: [{ type: "end", id: "e", status: "complete" }] });
      const c = coerceSurveyActions(m.build(sampleInputsFor(m)));
      const r = applySurveyActions(empty, c.actions);
      return { def: r.def, errors: [...c.rejected.map((x) => String((x as { reason?: string }).reason ?? x)), ...r.errors] };
    } catch (e) { return { def: null, errors: [(e as Error).message] }; }
  }, [m]);
  const design = built.def?.designs?.[0];
  return (
    <div className="dm" data-testid={`study-method-${m.id}`}>
      <div className="dm-head"><h3>{m.name}</h3><p className="dm-desc">Best for {m.fit}. Sample: {m.sample.note} · {m.loi}.</p></div>
      <div className="sd-pros"><div><b>Strengths</b><ul>{m.strengths.map((x) => <li key={x}>{x}</li>)}</ul></div><div><b>Trade-offs</b><ul>{m.tradeoffs.map((x) => <li key={x}>{x}</li>)}</ul></div><div><b>Analysis</b><ul>{m.analysis.map((x) => <li key={x}>{x}</li>)}</ul></div></div>
      <div className="dm-panel" data-testid="dm-study-sample">
        <b>Worked sample — built by the real study builder</b>
        {built.def ? (
          <>
            <p className="dm-desc">{built.def.questions.length} question{built.def.questions.length === 1 ? "" : "s"}{built.def.designs?.length ? `, ${built.def.designs.length} design file${built.def.designs.length === 1 ? "" : "s"}` : ""}, with the logic and randomisation the method needs:</p>
            <ol className="dm-qs">{built.def.questions.slice(0, 10).map((q) => <li key={q.id}><b>{q.code}</b> {String(q.text).replace(/<[^>]+>/g, " ").slice(0, 140)}</li>)}</ol>
            {built.def.questions.length > 10 && <p className="dm-desc">…and {built.def.questions.length - 10} more.</p>}
            {design?.file && <DesignPreview kind={design.kind} file={design.file as never} />}
          </>
        ) : <p className="sd-warn">{built.errors.join(" ")}</p>}
      </div>
      <div className="row" style={{ gap: 8 }}>
        <button type="button" className="btn primary small" data-testid="dm-open-study" onClick={() => { setPendingMethodology({ objective: "", methodId: m.id }); cmd?.context.setTab("studydesign"); }}>Configure and add it in Study design</button>
        <span className="dm-desc">Your own inputs, a check of the built study and a simulation, then one undoable step adds it to the survey.</span>
      </div>
    </div>
  );
}
