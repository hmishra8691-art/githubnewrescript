import test from "node:test";
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SurveyDefinition } from "@rescript/schema";
import { createResponseState, evaluateCondition } from "./index.js";
import { OPERATOR_COMPAT_SNAPSHOT } from "./operatorCompat.snapshot.js";

/**
 * BACKWARD COMPATIBILITY OF EVERY PRE-EXISTING OPERATOR (October 2026, smart operators).
 *
 * The snapshot was taken from the evaluator BEFORE the smart-operator work
 * (list-item operators, operator menus) touched it. Every operator that existed
 * then is evaluated against a fixed matrix of left-hand values (text, list
 * text, arrays, numbers, booleans, dates, clock times, grid maps, nothing) ×
 * right-hand values × second values, through `evaluateCondition`, the one path
 * every feature uses. One character per evaluation; a single changed answer
 * fails the test and names the case.
 *
 * Regenerate ONLY when an evaluation change is intended and reviewed:
 *   WRITE_OPERATOR_SNAPSHOT=1 node --test dist/operatorCompat.test.js
 */

export const LEGACY_OPERATORS = [
  "eq", "ne", "gt", "lt", "gte", "lte", "in", "notIn", "contains", "notContains",
  "answered", "unanswered", "selected", "notSelected", "between", "matches",
  "startsWith", "endsWith", "isEmpty", "isNotEmpty", "notBetween",
  "containsAny", "containsAll", "containsNone",
  "rankedFirst", "rankedLast", "rankedTopN", "rankEquals", "rankGreaterThan", "rankLessThan", "notRanked",
  "displayed", "notDisplayed", "dateBefore", "dateAfter", "dateEquals", "dateBetween",
] as const;

const LEFTS: unknown[] = [
  null, "", "abc", "Blue", "blue sky", "10001, 10002, 10003", "110001, 20002", "10001,10003",
  "02108", "02108, 02109", 5, "5", 0, -2.5, true, false, ["a", "b"], ["Blue"], [], ["10001", "10003"],
  "2026-01-05", "09:30", { r1: "1", r2: "2" }, "a; b\nc",
];
const RIGHTS: unknown[] = [
  undefined, "", "b", "blue", "10001", "10001, 10003", "1000", "02108", 2108, 5, "5", ["a"], ["a", "c"],
  ["10001", "99999"], "2026-01-01", "09:00", true, "^[0-9]+$",
];
const RIGHT2S: unknown[] = [undefined, 10, "2026-12-31", "17:00"];

const def = SurveyDefinition.parse({
  meta: { id: "compat", code: "C", title: "Compat", version: "1" },
  questions: [{ id: "q1", code: "Q1", variableName: "Q1", type: "text", text: "a" }],
  flow: [{ type: "page", id: "p1", questionIds: ["q1"] }],
  embeddedData: [{ name: "X" }],
});

export function operatorMatrix(): string {
  let out = "";
  for (const op of LEGACY_OPERATORS) {
    for (const left of LEFTS) {
      const state = createResponseState(def, { seed: 1, embedded: { X: left as never } });
      for (const value of RIGHTS) {
        for (const value2 of RIGHT2S) {
          let r: string;
          try {
            r = evaluateCondition(
              { type: "rule", source: { kind: "embedded", ref: "X" }, operator: op as never, value, value2 },
              { def, state, loop: null },
            ) ? "1" : "0";
          } catch {
            r = "E";
          }
          out += r;
        }
      }
    }
  }
  return out;
}

test("every pre-existing operator evaluates exactly as it did before the smart-operator work", () => {
  const now = operatorMatrix();
  if (process.env.WRITE_OPERATOR_SNAPSHOT === "1") {
    const file = fileURLToPath(new URL("../src/operatorCompat.snapshot.ts", import.meta.url));
    writeFileSync(file, `/* generated by operatorCompat.test.ts — do not edit by hand */\nexport const OPERATOR_COMPAT_SNAPSHOT = ${JSON.stringify(now)};\n`);
    return;
  }
  assert.equal(now.length, OPERATOR_COMPAT_SNAPSHOT.length, "the matrix itself changed shape");
  const per = LEFTS.length * RIGHTS.length * RIGHT2S.length;
  for (let i = 0; i < now.length; i++) {
    if (now[i] !== OPERATOR_COMPAT_SNAPSHOT[i]) {
      const op = LEGACY_OPERATORS[Math.floor(i / per)];
      const rest = i % per;
      const left = LEFTS[Math.floor(rest / (RIGHTS.length * RIGHT2S.length))];
      const value = RIGHTS[Math.floor((rest % (RIGHTS.length * RIGHT2S.length)) / RIGHT2S.length)];
      const value2 = RIGHT2S[rest % RIGHT2S.length];
      assert.fail(`${op}: ${JSON.stringify(left)} vs ${JSON.stringify(value)} / ${JSON.stringify(value2)} was ${OPERATOR_COMPAT_SNAPSHOT[i]}, now ${now[i]}`);
    }
  }
});
