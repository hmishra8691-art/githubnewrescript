
/**
 * THE STAMP ON A DELIVERED DOCUMENT (DOC-13).
 *
 * A document that says only "exported 2026-10-16" cannot answer the question
 * a reviewer asks six weeks later: is this the questionnaire that went to
 * field? Three facts answer it — WHEN to the minute, WHICH revision of the
 * survey row, and a short hash of the definition the document was written
 * from. Two documents with the same hash describe the same questionnaire,
 * whatever their dates; two with different hashes do not, whatever their
 * titles say.
 */

/** JSON with every object's keys sorted, so equal definitions always serialise to the same string. */
export function stableJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(",")}]`;
  if (value && typeof value === "object") {
    const o = value as Record<string, unknown>;
    return `{${Object.keys(o).filter((k) => o[k] !== undefined).sort().map((k) => `${JSON.stringify(k)}:${stableJson(o[k])}`).join(",")}}`;
  }
  return JSON.stringify(value) ?? "null";
}


/**
 * SHA-256 in plain JS so this module is safe in the browser bundle (the
 * Studio's export dialog imports the exporters index; `node:crypto` is not
 * available there). Verified against node:crypto in stamp.test.ts.
 */
