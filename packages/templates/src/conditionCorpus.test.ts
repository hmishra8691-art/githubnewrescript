import test from "node:test";
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { Question, SurveyDefinition } from "@rescript/schema";
import { effectiveResponseModel } from "@rescript/schema";
import { createResponseState, embeddedCatalog, evaluateCondition, forEachConditionRoot } from "@rescript/engine";
import { SURVEY_TEMPLATES, buildScaleSurvey } from "./index.js";
import { CONDITION_CORPUS_SNAPSHOT } from "./conditionCorpus.snapshot.js";

/**
 * EXISTING SURVEYS' CONDITIONS EVALUATE EXACTLY AS BEFORE (smart operators, October 2026).
 *
 * Every condition in every template — display, skip, branch, quota, punch,
 * validation, masking, loop and option logic; whatever `forEachConditionRoot`
 * finds — is evaluated against six deterministic respondents per template.
 * The answers are made here, from each question's own option, row and type
 * definitions, so they depend on nothing but the template; the snapshot was
 * recorded from the evaluator BEFORE the smart-operator change. One character
 * per (condition, respondent).
 *
 * Regenerate only for an intended, reviewed evaluation change:
 *   WRITE_CORPUS_SNAPSHOT=1 node --test dist/conditionCorpus.test.js
 */

const NUMS = [0, 3, 7, 15, 42, 100];
const TEXTS = ["", "abc", "Yes", "10001", "hello world", "02108"];
const EMBEDDED = ["", "1", "panel", "10001, 10002", "true", "25"];

function answerFor(q: Question, k: number): unknown {
  const opts = (q.options ?? []).map((o) => o.code);
  const rows = (q.rows ?? []).map((r) => r.code);
  const n = opts.length;
  const model = effectiveResponseModel(q);
  switch (model) {
    case "single_choice": return n ? opts[k % n] : undefined;
    case "multiple_choice": return n ? [...new Set([opts[k % n], opts[(k + 1) % n]])].slice(0, k % 3 === 2 ? 1 : 2) : undefined;
    case "rank_order": return n ? opts.map((_, i) => opts[(i + k) % n]) : undefined;
    case "numeric": return NUMS[k];
    case "text":
      if (q.type === "date") return `2026-0${k + 1}-15`;
      if (q.type === "time") return `0${k + 4}:30`;
      return TEXTS[k] || undefined;
    case "per_row":
      if (!rows.length) return undefined;
      return Object.fromEntries(rows.map((r, i) => [r,
        q.type === "matrix_multi" ? (n ? [opts[(i + k) % n]] : [])
          : q.type === "matrix_numeric" ? NUMS[(i + k) % NUMS.length]
          : q.type === "matrix_text" ? TEXTS[(i + k) % TEXTS.length]
          : n ? opts[(i + k) % n] : undefined]));
    case "allocation": {
      const keys = n ? opts : rows;
      return keys.length ? Object.fromEntries(keys.map((c, i) => [c, i === k % keys.length ? 100 : 0])) : undefined;
    }
    case "fields":
      return rows.length ? Object.fromEntries(rows.map((r, i) => [r, q.type === "numeric_list" ? NUMS[(i + k) % NUMS.length] : TEXTS[(i + k) % TEXTS.length]])) : undefined;
    default: return undefined;
  }
}

function corpusOf(def: SurveyDefinition): string {
  const roots: unknown[] = [];
  forEachConditionRoot(def, (c) => roots.push(c));
  let out = "";
  for (let k = 0; k < 6; k++) {
    const embedded = Object.fromEntries(embeddedCatalog(def).map((e) => [e.name, EMBEDDED[k]]));
    const state = createResponseState(def, { seed: 1, sessionId: "s", embedded: embedded as never });
    for (const q of def.questions) {
      const a = answerFor(q, k);
      if (a !== undefined) state.answers[q.id] = a as never;
    }
    for (const c of roots) {
      let r: string;
      try { r = evaluateCondition(c as never, { def, state, loop: null, quotaCounts: {} }) ? "1" : "0"; } catch { r = "E"; }
      out += r;
    }
  }
  return out;
}

function corpus(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const t of SURVEY_TEMPLATES) out[t.key] = corpusOf(t.build(`corpus_${t.key}`));
  out.scale = corpusOf(buildScaleSurvey(60, "corpus_scale"));
  return out;
}

test("every template condition evaluates exactly as before the smart-operator work", () => {
  const now = corpus();
  if (process.env.WRITE_CORPUS_SNAPSHOT === "1") {
    const file = fileURLToPath(new URL("../src/conditionCorpus.snapshot.ts", import.meta.url));
    writeFileSync(file, `/* generated by conditionCorpus.test.ts — do not edit by hand */\nexport const CONDITION_CORPUS_SNAPSHOT: Record<string, string> = ${JSON.stringify(now, null, 1)};\n`);
    return;
  }
  const total = Object.values(now).reduce((a, s) => a + s.length, 0);
  assert.ok(total > 500, `the corpus is meaningful (${total} evaluations)`);
  for (const [key, bits] of Object.entries(CONDITION_CORPUS_SNAPSHOT)) {
    assert.equal(now[key], bits, `template ${key}: a stored condition now evaluates differently`);
  }
});
